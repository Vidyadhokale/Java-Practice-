import java.util.*;
public class Addition
{
    public static void main(String args[])
    {
        Scanner sc=new Scanner(System.in);
        System.out.println("Enter First Number:");
        int no1=sc.nextInt();
        System.out.println("Enter Second Number:");
        int no2=sc.nextInt();
        int add=no1+no2;
        System.out.println("Addition:"+add);
    }
}
